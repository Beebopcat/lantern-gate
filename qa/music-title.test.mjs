import {BASE,launch,newPage,ok,summary} from './lib.mjs';
const b=await launch();
const page=await newPage(b,{w:900,h:640});
await page.goto(BASE+'?vista=0');await page.waitForSelector('text=New Game');
const scores=()=>page.evaluate(()=>[...document.querySelectorAll('audio[data-score]')].map(a=>a.dataset.score+(a.paused?':paused':':playing')));
ok((await scores()).length===0,'silent on title before enabling');
await page.getByRole('button',{name:'Settings'}).click();
await page.waitForSelector('#track-setting');
await page.click('#music-toggle');await page.waitForTimeout(2000);
let s=await scores();ok(s.some(x=>/^(gate-at-dawn|lantern-hymn):playing$/.test(x)),'a title track plays on the title screen: '+s);
const first=s.find(x=>x.endsWith(':playing')).split(':')[0];
const other=first==='gate-at-dawn'?'lantern-hymn':'gate-at-dawn';
await page.selectOption('#track-setting',other);await page.waitForTimeout(2500);
s=await scores();ok(s.includes(other+':playing'),'picking the other title track switches at once: '+s+' (was '+first+')');
ok((await page.textContent('#now-playing')).includes('Now playing'),'now playing text: '+await page.textContent('#now-playing'));
await page.selectOption('#track-setting','dripstone');await page.waitForTimeout(2500);
s=await scores();ok(!s.includes('dripstone:playing')&&s.some(x=>/^(gate-at-dawn|lantern-hymn):playing$/.test(x)),'a cellar track does not take over the title screen: '+s);
await page.selectOption('#track-setting','auto');await page.click('[data-action=music-next]');await page.waitForTimeout(2500);
s=await scores();ok(s.some(x=>/^(gate-at-dawn|lantern-hymn):playing$/.test(x)),'next track stays on a title track: '+s);
ok(page.errors.length===0,'no page errors '+page.errors);
process.exit(summary()?1:0);
