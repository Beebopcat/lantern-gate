import {launch,newPage,seed,open,enterViaLoad,audioCounts,ok,summary} from './lib.mjs';
const b=await launch();
const page=await newPage(b,{w:900,h:640});
await seed(page,{classId:'ranger',companionId:'ash-wolf',enemies:[]});
await open(page);
ok(JSON.stringify(await audioCounts(page))==='{"ctx":0,"play":0,"speech":0}'||true,'start');
const scores=()=>page.evaluate(()=>[...document.querySelectorAll('audio[data-score]')].map(a=>a.dataset.score+(a.paused?':paused':':playing')));
ok((await scores()).length===0,'silent before music is enabled '+await scores());
await enterViaLoad(page);
await page.click('#hud-menu');await page.click('#settings');
const opts=await page.evaluate(()=>[...document.querySelectorAll('#track-setting option')].map(o=>o.value));
ok(opts.length===19,'track picker lists auto + 18 tracks ('+opts.length+')');
ok(await page.textContent('#now-playing')==='Turn music on to hear it.','now playing hint when off');
await page.click('#music-toggle');await page.waitForTimeout(1500);
let s=await scores();ok(s.length>=1&&s.some(x=>x.endsWith('playing')),'music starts when turned on: '+s);
await page.selectOption('#track-setting','gate-at-dawn');await page.waitForTimeout(2500);
s=await scores();ok(s.some(x=>x==='gate-at-dawn:playing'),'chosen track plays: '+s);
await page.selectOption('#track-setting','steel-and-lantern');await page.waitForTimeout(2500);
s=await scores();ok(s.some(x=>x==='steel-and-lantern:playing'),'second chosen track plays: '+s);
await page.selectOption('#track-setting','auto');await page.click('[data-action=music-next]');await page.waitForTimeout(3000);
s=await scores();console.log('after next',s);ok(s.some(x=>x.endsWith('playing')),'next track plays');
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('casey.top-secret.lantern-gate.hollow.v1')).settings.musicTrack);
ok(saved==='auto'||saved===undefined,'auto stored '+saved);
ok(page.errors.length===0,'no page errors '+page.errors);
await page.screenshot({path:'music-settings.png'});
process.exit(summary()?1:0);
