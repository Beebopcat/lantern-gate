import re,colorsys,sys,tinycss2
src=open(sys.argv[1],encoding='utf-8').read()
HEX=re.compile(r'#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b')
RGB=re.compile(r'rgba?\(\s*([\d.]+)\s*[, ]\s*([\d.]+)\s*[, ]\s*([\d.]+)\s*(?:[,/]\s*([\d.]+%?)\s*)?\)')
NAMED={'white':'#ffffff'}
def parse_hex(h):
    h=h[1:]
    if len(h)in(3,4):h=''.join(c*2 for c in h)
    r,g,b=int(h[0:2],16),int(h[2:4],16),int(h[4:6],16);a=int(h[6:8],16)/255 if len(h)==8 else 1.0
    return r,g,b,a
def hls(r,g,b):
    h,l,s=colorsys.rgb_to_hls(r/255,g/255,b/255);return h,l,s
def to_hex(r,g,b,a=1.0):
    r,g,b=[max(0,min(255,round(x))) for x in (r,g,b)]
    return '#%02x%02x%02x'%(r,g,b) if a>=.999 else 'rgba(%d,%d,%d,%.3g)'%(r,g,b,a)
def from_hls(h,l,s):
    r,g,b=colorsys.hls_to_rgb(h,max(0,min(1,l)),max(0,min(1,s)));return r*255,g*255,b*255
# surface ramp (blue-grey, matches the existing dark Steam/folder pages)
def dark_bg(r,g,b,a):
    h,l,s=hls(r,g,b)
    if s>.38 and l<.9: return None            # saturated pastel tiles stay as they are
    if a<.999:                                  # translucent: mostly-opaque panels go dark, light veils become faint
        if l<=.85: return None
        if a<.5: return to_hex(255,255,255,min(a,1)*.07)
    if l<.62: return None
    if l>=.985: t=0
    elif l>=.95: t=.35
    elif l>=.92: t=.6
    elif l>=.88: t=.8
    else: t=1
    base=[(23,29,37),(27,35,48),(31,42,56),(36,50,68)]
    f=t*3;i=int(f);j=min(3,i+1);k=f-i
    return to_hex(*[base[i][c]*(1-k)+base[j][c]*k for c in range(3)],a)
def light_text(r,g,b,a):
    h,l,s=hls(r,g,b)
    if l>.62: return None
    if s>=.22:                                   # dark accents (greens/blues) -> readable tint, keep hue
        return to_hex(*from_hls(h,.70,min(.55,s+.1)),a)
    if l<=.16: return to_hex(236,242,246,a)
    if l<=.3: return to_hex(205,217,226,a)
    if l<=.45: return to_hex(168,184,196,a)
    return to_hex(150,166,178,a)
def dark_border(r,g,b,a):
    h,l,s=hls(r,g,b)
    if l<.7: return None
    if a<.999:return None
    return to_hex(*[(42,58,74)[c]*(0.7+0.3*(1-l)/.3 if l>.85 else 1) for c in range(3)]) if False else ('#2a3a4a' if l>.8 else '#3a4c5c')
def sub(value,fn):
    changed=[False]
    def rep_hex(m):
        r,g,b,a=parse_hex(m.group(0));n=fn(r,g,b,a)
        if n: changed[0]=True;return n
        return m.group(0)
    def rep_rgb(m):
        r,g,b=[float(m.group(i)) for i in (1,2,3)];a=m.group(4)
        a=1.0 if a is None else (float(a[:-1])/100 if a.endswith('%') else float(a))
        n=fn(r,g,b,a)
        if n: changed[0]=True;return n
        return m.group(0)
    v=RGB.sub(rep_rgb,value);v=HEX.sub(rep_hex,v)
    v=re.sub(r'(?<![\w#-])white(?![\w-])',lambda m:(fn(255,255,255,1.0) or m.group(0)),v)
    if v!=value: changed[0]=True
    return v,changed[0]
SKIP_SEL=re.compile(r'icon-tile|note-short|desktop-note|desktop-icon|\.desktop-|#desktop|\.wallpaper|#power-scene|\.rain|\.skip-link|\.monogram|\.tiny-squares|\.preview-label|^body$|^html$|:root|\.windows-mark|\.noscript')

def decl_fix(d):
    n=d.lower_name;val=tinycss2.serialize(d.value).strip()
    if n in('background','background-color','background-image'): v,c=sub(val,dark_bg)
    elif n=='color': v,c=sub(val,light_text)
    elif n in('border','border-top','border-bottom','border-left','border-right','border-color','border-block','border-inline','border-block-start','border-block-end','border-top-color','border-bottom-color','border-left-color','border-right-color','outline','outline-color'): v,c=sub(val,dark_border)
    else: return None
    return (n,v,d.important) if c else None
out=[];stats={'rules':0}
def handle_rule(rule,ind=''):
    sel=tinycss2.serialize(rule.prelude).strip()
    parts=[p.strip() for p in sel.split(',')]
    keep=[p for p in parts if not SKIP_SEL.search(p)]
    if not keep:return None
    decls=tinycss2.parse_declaration_list(rule.content,skip_comments=True,skip_whitespace=True)
    fixed=[x for x in (decl_fix(d) for d in decls if d.type=='declaration') if x]
    if not fixed:return None
    stats['rules']+=1
    return ind+','.join(keep)+'{'+';'.join(f'{n}:{v}'+(' !important' if imp else '') for n,v,imp in fixed)+'}'
rules=tinycss2.parse_stylesheet(src,skip_comments=True,skip_whitespace=True)
for r in rules:
    if r.type=='qualified-rule':
        s=handle_rule(r)
        if s:out.append(s)
    elif r.type=='at-rule' and r.lower_at_keyword=='media':
        prel=tinycss2.serialize(r.prelude).strip()
        if 'print' in prel: continue
        inner=tinycss2.parse_rule_list(r.content,skip_comments=True,skip_whitespace=True)
        parts=[handle_rule(x) for x in inner if x.type=='qualified-rule']
        parts=[p for p in parts if p]
        if parts: out.append('@media '+prel+'{'+''.join(parts)+'}')
